  function lang() { return document.documentElement.lang === 'en' ? 'en' : 'ko'; }

  /* t('readyCount', { n: 1, m: 3 }) → "완성 1 / 3" */
  function t(key, vars) {
    var d = DICT[lang()];
    var s = (key in d) ? d[key] : (DICT.ko[key] || key);
    if (vars) s = s.replace(/\{(\w+)\}/g, function (_, k) { return k in vars ? vars[k] : ''; });
    return s;
  }

  function apply(root) {
    root = root || document;
    var els = root.querySelectorAll('[data-i18n]');
    for (var i = 0; i < els.length; i++) els[i].textContent = t(els[i].getAttribute('data-i18n'));
    var attrs = root.querySelectorAll('[data-i18n-attr]');
    for (var j = 0; j < attrs.length; j++) {
      attrs[j].getAttribute('data-i18n-attr').split(';').forEach(function (pair) {
        var p = pair.split(':');
        if (p.length === 2) attrs[j].setAttribute(p[0].trim(), t(p[1].trim()));
      });
    }
  }

  window.I18N = { t: t, apply: apply, lang: lang, dict: DICT };
